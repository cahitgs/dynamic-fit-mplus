// build-exe.mjs — packs Dynamic Fit for Mplus into ONE Windows executable (Node "single executable application"):
// dist/DynamicFitMplus.exe. Double-click it on a computer with Mplus: it serves the interface from the embedded
// files, opens the browser and runs Mplus locally; projects are written to projects\ next to the .exe.
//   node tools/build-exe.mjs                 → dist/DynamicFitMplus.exe
//   node tools/build-exe.mjs --name X        → dist/X.exe
// Needs Node 20.12+ on the building machine (the .exe embeds this Node runtime, ~100 MB) and, the first time,
// network access (npx downloads postject, which injects the application blob).
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argName = process.argv.indexOf('--name');
const NAME = (argName > 0 && process.argv[argName + 1] && !process.argv[argName + 1].startsWith('-')) ? process.argv[argName + 1] : 'DynamicFitMplus';
const POSTJECT = 'postject@1.0.0-alpha.6'; // pinned: every build injects with the same tool
const FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';
const BUILD = path.join(ROOT, 'build');
const DIST = path.join(ROOT, 'dist');
fs.mkdirSync(BUILD, { recursive: true });
fs.mkdirSync(DIST, { recursive: true });

// ---- 1 · the files the server sends to the browser: public/ and data/ ----------------------------
const EXT = new Set(['.html', '.css', '.js', '.mjs', '.json', '.csv', '.svg', '.png', '.ico', '.woff', '.woff2', '.txt']);
const assets = {};
function add(rel) {
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) return;
  const st = fs.statSync(abs);
  if (st.isDirectory()) { for (const f of fs.readdirSync(abs)) add(path.posix.join(rel, f)); return; }
  if (EXT.has(path.extname(rel).toLowerCase())) assets[rel] = abs;
}
['public', 'data'].forEach(add);
const keys = Object.keys(assets).sort();
fs.writeFileSync(path.join(BUILD, 'assets.json'), JSON.stringify(keys));
const total = keys.reduce((n, k) => n + fs.statSync(assets[k]).size, 0);
console.log(`  ${keys.length} files, ${(total / 1048576).toFixed(2)} MB to embed`);

// ---- 2 · one CommonJS entry: engines.mjs as an inner module, then serve.mjs inside an async function ----
const toRequire = (code) => code
  .replace(/^import (\w+) from '(node:[\w/]+)';$/gm, "const $1 = require('$2');")
  .replace(/^import \{([^}]+)\} from '(node:[\w/]+)';$/gm, "const {$1} = require('$2');");

let engines = toRequire(fs.readFileSync(path.join(ROOT, 'engines.mjs'), 'utf8'));
const exported = [...engines.matchAll(/^export (?:async )?(?:const|let|function|class) (\w+)/gm)].map((m) => m[1]);
engines = engines.replace(/^export (?=(?:async )?(?:const|let|function|class) )/gm, '');

let serve = toRequire(fs.readFileSync(path.join(ROOT, 'serve.mjs'), 'utf8'))
  .replace(/^import \{([^}]+)\} from '\.\/engines\.mjs';$/m, 'const {$1} = __engines;')
  .replace(/fileURLToPath\(import\.meta\.url\)/g, 'process.execPath');
for (const [name, code] of [['engines.mjs', engines], ['serve.mjs', serve]]) {
  if (/^\s*(import|export)\s/m.test(code) || /import\.meta/.test(code)) throw new Error(`${name} still contains import/export statements the build cannot convert.`);
}

const entry = `'use strict';
// generated by tools/build-exe.mjs — do not edit
const __sea = require('node:sea');
const __keys = JSON.parse(__sea.getAsset('__assets__', 'utf8'));
globalThis.__SEA__ = { assets: new Map(__keys.map((k) => [k, () => Buffer.from(__sea.getAsset(k))])) };
const __engines = (() => {
${engines}
return { ${exported.join(', ')} };
})();
(async () => {
${serve}
})().catch((e) => { console.error(e); process.exitCode = 1; });
`;
const entryPath = path.join(BUILD, 'entry.cjs');
fs.writeFileSync(entryPath, entry);
execFileSync(process.execPath, ['--check', entryPath], { stdio: 'inherit' });

// ---- 3 · the SEA blob -------------------------------------------------------------------------------
const blobPath = path.join(BUILD, 'sea-prep.blob');
const cfg = {
  main: entryPath, output: blobPath, disableExperimentalSEAWarning: true, useCodeCache: true,
  assets: { __assets__: path.join(BUILD, 'assets.json'), ...assets },
};
const cfgPath = path.join(BUILD, 'sea-config.json');
fs.writeFileSync(cfgPath, JSON.stringify(cfg, null, 2));
console.log('  generating the blob …');
execFileSync(process.execPath, ['--experimental-sea-config', cfgPath], { stdio: 'inherit', cwd: ROOT });

// ---- 4 · copy this Node runtime and inject the blob ----------------------------------------------
const exePath = path.join(DIST, `${NAME}${process.platform === 'win32' ? '.exe' : ''}`);
fs.copyFileSync(process.execPath, exePath);
console.log('  injecting the blob with postject …');
const q = (s) => `"${s}"`;
const r = spawnSync(`npx --yes ${POSTJECT} ${q(exePath)} NODE_SEA_BLOB ${q(blobPath)} --sentinel-fuse ${FUSE}`, { stdio: 'inherit', cwd: ROOT, shell: true });
if (r.status !== 0) throw new Error(`postject failed (exit ${r.status})`);
const mb = (fs.statSync(exePath).size / 1048576).toFixed(0);
console.log(`\n  ready: ${exePath} (${mb} MB, Node ${process.version} inside)`);
console.log(`  run it: double-click, or from a terminal  ${path.basename(exePath)} [--no-open]   (PORT=… to choose the port)`);
